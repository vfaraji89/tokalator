// Generates src/core/catalog.generated.ts from the extension's models.json and copies the
// shared Claude Code log parser. Runs before every build; skips when the extension folder is absent.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ext = join(root, '..', 'tokalator-extension-vs');
const modelsJson = join(ext, 'models.json');
const parser = join(ext, 'src', 'core', 'claudeCodeUsage.pure.ts');

if (!existsSync(modelsJson) || !existsSync(parser)) {
  console.log('sync: extension sources not found, keeping committed copies');
  process.exit(0);
}

const catalog = JSON.parse(readFileSync(modelsJson, 'utf8'));
const claude = catalog.models
  .filter(m => m.provider === 'anthropic')
  .map(m => ({
    id: m.id,
    label: m.label,
    contextWindow: m.contextWindow,
    maxOutput: m.maxOutput,
    rotThreshold: m.rotThreshold,
    inputCostPerMTok: m.inputCostPerMTok,
    outputCostPerMTok: m.outputCostPerMTok,
    cachedInputCostPerMTok: m.cachedInputCostPerMTok,
    ...(m.cacheWriteCostPerMTok !== undefined && { cacheWriteCostPerMTok: m.cacheWriteCostPerMTok }),
    ...(m.longContext && { longContext: m.longContext }),
  }));
const defaultId = claude.some(m => m.id === catalog.defaultModelId) ? catalog.defaultModelId : claude[0].id;

writeFileSync(join(root, 'src', 'core', 'catalog.generated.ts'), `// Generated by scripts/sync.mjs from tokalator-extension-vs/models.json. Do not edit.
export const CATALOG_UPDATED_AT = ${JSON.stringify(catalog.updatedAt)};
export const DEFAULT_MODEL_ID = ${JSON.stringify(defaultId)};
export const CLAUDE_CATALOG = ${JSON.stringify(claude, null, 2)} as const;
`);
writeFileSync(join(root, 'src', 'core', 'claudeCodeUsage.pure.ts'),
  '// Copied from tokalator-extension-vs/src/core/claudeCodeUsage.pure.ts by scripts/sync.mjs. Do not edit.\n' + readFileSync(parser, 'utf8'));
console.log(`sync: ${claude.length} Claude models, parser copied`);
